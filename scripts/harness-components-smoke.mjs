// Exercise component registration/disposal against actual installed Harness services.
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { mkdtemp, mkdir, cp, symlink, rm } from 'node:fs/promises'
const runtime = process.env.DSH_RUNTIME_ROOT
assert.ok(runtime, 'Set DSH_RUNTIME_ROOT to installed node_modules/@deepseek-ai')
const host = name => import(pathToFileURL(`${runtime}/${name}/lib/index.js`))
const { Context } = await host('cordis')
const { LlmRuntime } = await host('dsh-llm')
const { WebRuntime } = await host('dsh-web')
const { ToolRuntime } = await host('dsh-tools')
const root = await mkdtemp('/tmp/dsh-components-runtime-')
try {
  await mkdir(`${root}/node_modules`)
  await symlink(runtime, `${root}/node_modules/@deepseek-ai`)
  await cp(new URL('../lib', import.meta.url), `${root}/lib`, { recursive: true })
  const component = async file => (await import(pathToFileURL(`${root}/lib/${file}.js`))).default
  const ctx = new Context()
  ctx.provide('sessions', { get() {} })
  ctx.provide('attachments', {})
  ctx.provide('systemPrompt', { tools() {} })
  const llm = new LlmRuntime(ctx)
  const web = new WebRuntime(ctx, { searchProvider: { get() {} }, fetchProvider: { get() {} } })
  const tools = new ToolRuntime(ctx)
  const runtimePlugin = ctx.plugin({ name: 'fixture-runtime', apply(ctx) { ctx.provide('codexRuntime', { server: {} }) } })
  await runtimePlugin.await()
  const modules = await Promise.all(['index', 'component-search', 'component-fetch', 'component-images'].map(component))
  const fibers = modules.map(module => ctx.plugin(module))
  await Promise.all(fibers.map(fiber => fiber.await()))
  const checkAll = () => {
    assert.equal(llm.listProviders().length, 1)
    assert.equal(web.searchProviders.size, 1)
    assert.equal(web.fetchProviders.size, 1)
    assert.ok(tools.get('image_generate'))
    assert.ok(tools.get('image_edit'))
  }
  checkAll()
  await fibers[1].dispose()
  assert.equal(web.searchProviders.size, 0)
  assert.equal(web.fetchProviders.size, 1)
  assert.equal(llm.listProviders().length, 1)
  assert.ok(tools.get('image_generate'))
  await assert.rejects(web.search({ query: 'test' }), error => error.code === 'WEB_PROVIDER_UNAVAILABLE')
  fibers[1] = ctx.plugin(modules[1])
  await fibers[1].await()
  checkAll()
  for (const fiber of fibers) { await fiber.restart(); checkAll() }
  await fibers[3].dispose()
  assert.equal(tools.get('image_generate'), undefined)
  assert.equal(tools.get('image_edit'), undefined)
  assert.equal(llm.listProviders().length, 1)
  fibers[3] = ctx.plugin(modules[3])
  await fibers[3].await()
  checkAll()
  await runtimePlugin.dispose()
  await Promise.all(fibers.map(fiber => fiber.await()))
  assert.equal(llm.listProviders().length, 0)
  assert.equal(web.searchProviders.size, 0)
  assert.equal(web.fetchProviders.size, 0)
  assert.equal(tools.get('image_generate'), undefined)
  const resumed = ctx.plugin({ name: 'fixture-runtime-resumed', apply(ctx) { ctx.provide('codexRuntime', { server: {} }) } })
  await resumed.await()
  await Promise.all(fibers.map(fiber => fiber.await()))
  checkAll()
  for (const fiber of fibers) await fiber.dispose()
  await resumed.dispose()
  console.log(JSON.stringify({ independentSearch: 'PASS', independentImages: 'PASS', restartWithoutDuplicates: 'PASS', runtimeDependencyStopAndResume: 'PASS' }, null, 2))
} finally { await rm(root, { recursive: true, force: true }) }
